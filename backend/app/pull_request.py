#Turns an approved analysis into a draft pull request. Only runs after a human approves,
#and only edits the workflow file that failed. The PR is always a draft; nothing is merged.
import json

from sqlalchemy.orm import Session

from app.analysis import MAX_FILE_CHANGES, FileChange
from app.github_client import GitHubClient
from app.models import JobFailure

MAX_CONTENT_CHARS = 100_000


class PullRequestError(Exception):
    pass


def open_draft_pr(db: Session, job: JobFailure, gh: GitHubClient) -> str:
    if job.status != "APPROVED":
        raise PullRequestError(f"Job is {job.status}; only APPROVED jobs can open a PR")
    if job.pr_url:
        raise PullRequestError(f"A PR already exists: {job.pr_url}")

    changes = [FileChange(**item) for item in json.loads(job.proposed_changes or "[]")]
    _validate(job, changes)

    failure = job.workflow_failure
    repo = failure.repository.full_name
    run_id = failure.github_run_id
    branch = f"autodebug/run-{run_id}-job-{job.github_job_id}"

    # Read the originals first, so a no-op edit fails before anything is created on GitHub.
    originals = {change.path: gh.get_file(repo, change.path, job.head_sha) for change in changes}
    for change in changes:
        if originals[change.path][0] == change.content:
            raise PullRequestError(f"The proposed content for {change.path} changes nothing")

    gh.create_branch(repo, branch, job.head_sha)
    for change in changes:
        _, blob_sha = originals[change.path]
        gh.put_file(
            repo,
            change.path,
            branch,
            change.content,
            blob_sha,
            message=f"CI auto-fix for {job.job_name} (run {run_id})",
        )

    pr_url = gh.create_draft_pr(
        repo,
        head=branch,
        base=failure.repository.default_branch or "main",
        title=f"[CI auto-fix] {job.job_name} failed in run {run_id}",
        body=_pr_body(job, run_id, repo),
    )

    job.pr_url = pr_url
    job.status = "PR_OPENED"
    db.commit()
    return pr_url


def _validate(job: JobFailure, changes: list[FileChange]) -> None:
    if not changes:
        raise PullRequestError("The analysis proposed no file changes")
    if len(changes) > MAX_FILE_CHANGES:
        raise PullRequestError(f"Too many file changes ({len(changes)} > {MAX_FILE_CHANGES})")
    for change in changes:
        if change.path != job.workflow_path:
            raise PullRequestError(f"Changes to {change.path} are not allowed")
        if not change.content.strip():
            raise PullRequestError(f"Empty content for {change.path}")
        if len(change.content) > MAX_CONTENT_CHARS:
            raise PullRequestError(f"Content for {change.path} is too large")


def _pr_body(job: JobFailure, run_id: int, repo: str) -> str:
    reviewer = job.reviewed_by or "unknown"
    note = f"\n\nReviewer note: {job.review_note}" if job.review_note else ""
    return (
        "This draft was generated by CI Auto-Debug Agent and approved by "
        f"{reviewer} before opening. Review it like any other change.\n\n"
        f"**Failed run:** https://github.com/{repo}/actions/runs/{run_id}\n"
        f"**Job:** {job.job_name}  \n"
        f"**Failed step:** {job.failed_step or 'unknown'}  \n"
        f"**Analysis:** {job.failure_type or '-'}, confidence {job.confidence or '-'}\n\n"
        f"{job.error_summary or ''}"
        f"{note}"
    )


AUTO_FIX_BRANCH_PREFIX = "autodebug/"


def record_pull_request_event(
    db: Session,
    action: str | None,
    merged: bool,
    html_url: str | None,
    head_ref: str,
) -> bool:
    # Called from the webhook for pull_request events. Only auto-fix PRs we opened are tracked.
    if action != "closed" or not html_url or not head_ref.startswith(AUTO_FIX_BRANCH_PREFIX):
        return False
    job = db.query(JobFailure).filter(JobFailure.pr_url == html_url).first()
    if job is None:
        return False
    job.status = "MERGED" if merged else "PR_CLOSED"
    db.commit()
    return True
